const fold = (s) => String(s || '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();

/** Every gear key an entry uses, in signal order as it is laid on the board. */
export function famousGear(e) {
  return [...(e.pre || []).map((p) => p[0]), e.amp[0], e.cab, ...(e.post || []).map((p) => p[0]), ...(e.rack || []).map((p) => p[0])].filter(Boolean);
}

/**
 * The tone an entry makes, in the same shape as every other tone (saved tones, song tones,
 * Create a Tone): the same sound engine, cabinet and loudness path.
 */
export function famousTone(e) {
  const gear = [];
  let o = 0;
  const add = (slot, [key, knobs, off]) => gear.push({ slot, key, knobs: { ...(knobs || {}) }, order: o++, ...(off ? { bypass: true } : {}) });
  for (const p of e.pre || []) add('pre', p);
  add('amp', e.amp);
  if (e.cab) add('cab', [e.cab, {}]);
  for (const p of e.post || []) add('post', p);
  for (const p of e.rack || []) add('rack', p);
  return { name: e.name, kind: e.kind, gear, cabId: e.cabFile || null, ir: null, autoCab: true, capture: null };
}

/** The words an entry is found by. */
export function famousText(e) {
  return fold([e.name, e.after, (e.tags || []).join(' '), e.words, e.pickup, e.why].join(' '));
}

/**
 * Search by player, band, song, genre or any word. Every word typed has to match somewhere.
 * kind: 'guitar' | 'bass' | null (both); genre: one of GENRES or ''.
 * Best first: name, then who it's after, then the rest.
 */
export function searchFamous(q = '', { kind = null, genre = '' } = {}) {
  const words = fold(q).split(/[^a-z0-9/+'-]+/).map((w) => w.replace(/^'+|'+$/g, '')).filter(Boolean);
  const list = FAMOUS.filter((e) => (!kind || e.kind === kind) && (!genre || (e.tags || []).includes(genre)));
  if (!words.length) return list;
  const scored = [];
  for (const e of list) {
    const all = famousText(e);
    if (!words.every((w) => all.includes(w))) continue;
    const name = fold(e.name), after = fold(e.after), tags = fold((e.tags || []).join(' '));
    let s = 0;
    for (const w of words) s += name.includes(w) ? 6 : after.includes(w) ? 4 : tags.includes(w) ? 3 : 1;
    scored.push([s, e]);
  }
  return scored.sort((a, b) => b[0] - a[0]).map(([, e]) => e);
}
